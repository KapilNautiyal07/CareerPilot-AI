"use client";

import { MessagesSquare, Play } from "lucide-react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useState } from "react";

import { Button } from "@/components/ui/button";
import { Alert, Badge, Card, CardContent, CardDescription, CardHeader, CardTitle, Field, Input, Select } from "@/components/ui/primitives";
import { EmptyState, ErrorState, LoadingCards, PageHeader } from "@/components/ui/states";
import { api, errorMessage } from "@/lib/api";
import { useInterviews, useProfile } from "@/lib/queries";
import { formatDateTime, scoreTone, titleCase } from "@/lib/utils";
import type { InterviewSession } from "@/types/api";

const CATEGORIES = [
  { value: "mixed", label: "Mixed (based on your target role)" },
  { value: "dsa", label: "Data structures & algorithms" },
  { value: "python", label: "Python" },
  { value: "backend", label: "Backend engineering" },
  { value: "system_design", label: "System design" },
  { value: "behavioral", label: "Behavioral" },
  { value: "project", label: "Project discussion" },
];

export default function InterviewsPage() {
  const router = useRouter();
  const profile = useProfile();
  const sessions = useInterviews();
  const [category, setCategory] = useState("mixed");
  const [difficulty, setDifficulty] = useState("medium");
  const [num, setNum] = useState(4);
  const [role, setRole] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function start(e: React.FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      const s = await api<InterviewSession>("/interviews", {
        body: { category, difficulty, num_questions: num, target_role: role || undefined },
      });
      router.push(`/interviews/${s.id}`);
    } catch (err) {
      setError(errorMessage(err));
      setBusy(false);
    }
  }

  return (
    <>
      <PageHeader title="Interview practice" description="Mock interviews one question at a time, graded against explicit rubrics. Results update your skill gaps and roadmap." />
      <div className="grid gap-6 lg:grid-cols-3">
        <Card className="lg:col-span-1">
          <CardHeader><CardTitle>Start a mock interview</CardTitle><CardDescription>Questions are chosen to target your current skill gaps.</CardDescription></CardHeader>
          <CardContent>
            <form onSubmit={start} className="space-y-4">
              <Field label="Category" htmlFor="category">
                <Select id="category" value={category} onChange={(e) => setCategory(e.target.value)}>
                  {CATEGORIES.map((c) => <option key={c.value} value={c.value}>{c.label}</option>)}
                </Select>
              </Field>
              <div className="grid grid-cols-2 gap-3">
                <Field label="Difficulty" htmlFor="difficulty">
                  <Select id="difficulty" value={difficulty} onChange={(e) => setDifficulty(e.target.value)}>
                    <option value="easy">Easy</option><option value="medium">Medium</option><option value="hard">Hard</option>
                  </Select>
                </Field>
                <Field label="Questions" htmlFor="num">
                  <Input id="num" type="number" min={1} max={8} value={num} onChange={(e) => setNum(Number(e.target.value))} />
                </Field>
              </div>
              <Field label="Target role" htmlFor="role" hint={`Defaults to ${profile.data?.target_role || "your profile role"}.`}>
                <Input id="role" value={role} onChange={(e) => setRole(e.target.value)} placeholder={profile.data?.target_role} />
              </Field>
              {error && <Alert tone="error">{error}</Alert>}
              <Button type="submit" className="w-full" loading={busy}><Play /> Start interview</Button>
              <p className="text-xs text-muted-foreground">Practice feedback is generated by CareerPilot&apos;s rubrics and is not an employer&apos;s assessment.</p>
            </form>
          </CardContent>
        </Card>

        <div className="lg:col-span-2">
          <h2 className="mb-3 text-sm font-medium text-muted-foreground">History</h2>
          {sessions.isLoading ? <LoadingCards count={2} className="sm:grid-cols-1 lg:grid-cols-1" /> : sessions.error ? <ErrorState error={sessions.error} /> : !sessions.data?.length ? (
            <EmptyState icon={MessagesSquare} title="No interviews yet" description="Your sessions and scores will appear here." />
          ) : (
            <ul className="space-y-2">
              {sessions.data.map((s) => {
                const tone = scoreTone(s.overall_score);
                return (
                  <li key={s.id}>
                    <Link href={`/interviews/${s.id}`} className="flex items-center gap-4 rounded-lg border bg-card p-4 hover:bg-muted/50">
                      <div className="min-w-0 flex-1">
                        <p className="font-medium">{titleCase(s.category)} · {s.target_role}</p>
                        <p className="text-xs text-muted-foreground">{formatDateTime(s.started_at)} · {s.questions.length} questions · {s.difficulty}</p>
                      </div>
                      {s.status === "in_progress" ? <Badge>In progress</Badge> : s.overall_score !== null ? (
                        <Badge variant={tone === "muted" ? "muted" : tone}>{Math.round(s.overall_score)}/100</Badge>
                      ) : <Badge variant="muted">{titleCase(s.status)}</Badge>}
                    </Link>
                  </li>
                );
              })}
            </ul>
          )}
        </div>
      </div>
    </>
  );
}
